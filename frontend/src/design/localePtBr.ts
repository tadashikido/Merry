import { defaultOptions, type PrimeVueLocaleOptions } from 'primevue/config'

function obterLocalePadrao(): PrimeVueLocaleOptions {
  if (!defaultOptions.locale) {
    throw new Error('Locale padrão do PrimeVue indisponível.')
  }
  return defaultOptions.locale
}

